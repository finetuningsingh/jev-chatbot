// Runs every chat mode on the same prompts and writes results/results.md (and .json)
// with each reply, its time, and its Jev cost. Usage: node eval.js
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { ensureKey } from './lib.js';
import { replyByLetters, replyByWords, replyByScoring, replyByTree, replyByReplyTree } from './chatbot.js';

const PROMPTS = [
  'hi what is capital of france',
  'hi how are you',
  'who are you',
  'can you recommend a good book',
  'tell me the meaning of life',
];

const MODES = [
  { name: 'letters', run: (h) => replyByLetters(h) },
  { name: 'letter-first (10k)', run: (h) => replyByWords(h) },
  { name: 'tree (30k)', run: (h) => replyByTree(h, undefined, { tree: 'tree-30k.json' }) },
  { name: 'wide tree (30k)', run: (h) => replyByTree(h, undefined, { tree: 'tree-30k-wide.json' }) },
  { name: 'scoring (10k)', run: (h) => replyByScoring(h, undefined, { vocab: '10k' }) },
  { name: 'scoring (30k)', run: (h) => replyByScoring(h, undefined, { vocab: '30k' }) },
  { name: 'reply tree', run: (h) => replyByReplyTree(h) },
];

await ensureKey();
// Results already saved are reused (pass --fresh to rerun everything), so a failed run
// doesn't pay twice for the modes that finished.
const JSON_FILE = new URL('./results/results.json', import.meta.url);
mkdirSync(new URL('./results/', import.meta.url), { recursive: true });
const saved = !process.argv.includes('--fresh') && existsSync(JSON_FILE) ? JSON.parse(readFileSync(JSON_FILE, 'utf8')) : [];
const rows = saved.filter((r) => MODES.some((m) => m.name === r.mode) && PROMPTS.includes(r.prompt));
for (const mode of MODES) {
  // Prompts run in parallel within a mode; modes run one after another.
  const todo = PROMPTS.filter((p) => !rows.some((r) => r.mode === mode.name && r.prompt === p));
  const results = await Promise.all(
    todo.map(async (prompt) => {
      const t0 = performance.now();
      const r = await mode.run([{ role: 'user', text: prompt }]);
      return { mode: mode.name, prompt, ...r, secs: (performance.now() - t0) / 1000 };
    }),
  );
  results.forEach((r) => console.log(`${r.mode.padEnd(20)} ${r.prompt.padEnd(30)} ${JSON.stringify(r.reply)}${r.stuck ? ' (loop)' : ''} ${r.secs.toFixed(1)}s $${r.cost.toFixed(4)}`));
  rows.push(...results);
  writeFileSync(JSON_FILE, JSON.stringify(rows, null, 2));
}

const esc = (s) => s.replace(/\|/g, '\\|');
const cell = (r) => `\`${esc(r.reply) || '(empty)'}\`${r.stuck ? ' (loop)' : ''}`;
let md = `# Results\n\nGenerated by \`node eval.js\` on ${new Date().toISOString().slice(0, 10)} with \`${process.env.JEV_MODEL ?? 'typesafe/jev-1.13'}\`.\n\n`;
md += `| Prompt | ${MODES.map((m) => m.name).join(' | ')} |\n| --- |${MODES.map(() => ' --- |').join('')}\n`;
for (const p of PROMPTS) md += `| ${p} | ${MODES.map((m) => cell(rows.find((r) => r.mode === m.name && r.prompt === p))).join(' | ')} |\n`;
md += `\n## Cost and time per reply\n\n| Mode | Jev calls | Avg time | Avg cost | Total for ${PROMPTS.length} prompts |\n| --- | --- | --- | --- | --- |\n`;
let grand = 0;
for (const m of MODES) {
  const rs = rows.filter((r) => r.mode === m.name);
  const total = rs.reduce((a, r) => a + r.cost, 0);
  grand += total;
  const avg = (f) => rs.reduce((a, r) => a + f(r), 0) / rs.length;
  md += `| ${m.name} | ${Math.round(avg((r) => r.calls))} | ${avg((r) => r.secs).toFixed(1)} s | $${avg((r) => r.cost).toFixed(4)} | $${total.toFixed(4)} |\n`;
}
md += `\nTotal Jev cost of this run: $${grand.toFixed(4)}.\n`;

writeFileSync(new URL('./results/results.md', import.meta.url), md);
console.log(`\nWrote results/results.md (total $${grand.toFixed(4)})`);
